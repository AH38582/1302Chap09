
public class Circle {
//	default data member radius
	double radius = 1.0;
	
//	behaviors for circle lines 8-18
	
	double getDiameter() {
		return Math.PI * radius * radius;
	}
	
	double getArea() {
		return Math.PI * radius * radius;
	}
	
	double getPerimeter() {
		return Math.PI * radius * 2;
	}
	
	
	

}
